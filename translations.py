# ---------------------------------------------------------------------------
# Language state
# ---------------------------------------------------------------------------

def set_language(lang: str) -> None:
    """Set the current UI language."""
    global _current_language
    _current_language = lang


def get_language() -> str:
    """Return the current UI language code."""
    return _current_language


def t(key: str, **kwargs) -> str:
    """
    Return the translated string for *key* in the current language.

    Supports Python format kwargs, e.g.::

        t("intro_default_text", n=3)  ->  "We gaan 3 foto's maken"

    Falls back to the Dutch text if the key exists but the current language
    is missing, or returns the key itself if unknown.
    """
    entry = TRANSLATIONS.get(key)
    if entry is None:
        return key
    text = entry.get(_current_language) or entry.get("nl", key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


# ---------------------------------------------------------------------------
# Persistence helpers
# ---------------------------------------------------------------------------

def save_language(lang: str) -> None:
    """Persist the chosen language to *settings.json*."""
    data = {}
    if os.path.exists(SETTINGS_FILE):
        try:
            with open(SETTINGS_FILE, "r", encoding="utf-8") as fh:
                data = json.load(fh)
        except (json.JSONDecodeError, OSError):
            data = {}
    data["language"] = lang
    os.makedirs(os.path.dirname(SETTINGS_FILE), exist_ok=True)
    with open(SETTINGS_FILE, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)


def load_language() -> str:
    """
    Load the language from *settings.json*.

    Returns the language code (e.g. ``"nl"``) or an empty string if the
    setting does not exist or the file is missing / corrupt.
    """
    if not os.path.exists(SETTINGS_FILE):
        return ""
    try:
        with open(SETTINGS_FILE, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        return data.get("language", "")
    except (json.JSONDecodeError, OSError):
        return ""
